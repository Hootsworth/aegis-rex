/**
 * aegis-rex/layers/egressMask.js
 * Layer 6: Honey-Token & Egress Mask (Zero-Leak Personal Redaction).
 * Scrubs outbound secrets and triggers tripwires on honey-token exfiltration attempts.
 */

import os from 'os';

export class EgressMask {
    constructor(config = {}) {
        this.enabled = config.enabled !== false;
        this.maskSecretKeys = config.maskSecretKeys !== false;
        this.redactLocalHomePaths = config.redactLocalHomePaths !== false;
        this.honeyToken = config.honeyToken || config.canaryHoneyToken || 'AEGIS_HONEY_TOKEN_77A_DO_NOT_EXFILTRATE';

        this.keyReplacements = [
            { pattern: /sk-[A-Za-z0-9_-]{20,}/g, tag: '[REDACTED_OPENAI_KEY]' },
            { pattern: /sk_car_[A-Za-z0-9_-]{20,}/g, tag: '[REDACTED_CARTESIA_KEY]' },
            { pattern: /AIzaSy[A-Za-z0-9_-]{33}/g, tag: '[REDACTED_GEMINI_KEY]' },
            { pattern: /ghp_[A-Za-z0-9]{36}/g, tag: '[REDACTED_GITHUB_PAT]' },
            { pattern: /gho_[A-Za-z0-9]{36}/g, tag: '[REDACTED_GITHUB_OAUTH]' }
        ];

        this.keyPatterns = config.keyPatterns || this.keyReplacements.map(k => k.pattern);
        this.homeDir = os.homedir();
    }

    /**
     * Inspect and sanitize outbound text before sending to Discord, Telegram, or voice TTS
     * @param {string} text - The raw reply text generated by the agent
     * @returns {{ sanitizedText: string, honeyTokenTripped: boolean, redactedCount: number }}
     */
    sanitizeOutput(text) {
        if (!this.enabled || !text) {
            return { sanitizedText: text, honeyTokenTripped: false, redactedCount: 0 };
        }

        let output = String(text);
        let honeyTokenTripped = false;
        let redactedCount = 0;

        // 1. Honey-Token Tripwire Check
        if (output.includes(this.honeyToken)) {
            honeyTokenTripped = true;
            output = `[SECURITY NOTICE: Honey-token exfiltration blocked by AEGIS-REX. Canary token: [TRIPWIRE_ALERT: ATTEMPTED_EXFILTRATION]]`;
        }

        // 2. Secret API Keys Scrubber
        if (this.maskSecretKeys) {
            for (const { pattern, tag } of this.keyReplacements) {
                if (pattern.test(output)) {
                    output = output.replace(pattern, () => {
                        redactedCount++;
                        return tag;
                    });
                }
            }

            // Fallback generic scanner if custom keyPatterns were passed
            for (const customPattern of this.keyPatterns) {
                if (customPattern.test(output)) {
                    output = output.replace(customPattern, () => {
                        redactedCount++;
                        return '[REDACTED_SECRET_KEY]';
                    });
                }
            }
        }

        // 3. Local Personal Home Directory Path Redaction
        if (this.redactLocalHomePaths && this.homeDir) {
            output = output.replaceAll(this.homeDir, '~');
        }

        return {
            sanitizedText: output,
            honeyTokenTripped,
            redactedCount
        };
    }
}
